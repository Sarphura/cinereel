#!/usr/bin/env node
/**
 * gen-hyper-agent-client.mjs — deterministic Node equivalent of NSwag's
 * `openapi2csclient` for the Hyper Agent. NSwag itself is a .NET tool
 * we do not assume is on every dev machine; this script reads the
 * committed OpenAPI snapshot and emits a stable
 * `HyperAgentClient.g.cs` so the drift check can run offline.
 *
 * Inputs:
 *   apps/hyper-agent/test/openapi.snapshot.json
 * Outputs:
 *   apps/service/src/HyperAgent/HyperAgentClient.g.cs
 *
 * Ticket 14 specifies that any controller change must regenerate this
 * file; `scripts/check-nswag-drift.mjs` is the verifier.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const HERE = join(__dirname, '..')

const SNAPSHOT = process.argv[2] ?? join(
  HERE,
  'apps/hyper-agent/test/openapi.snapshot.json',
)
const OUT = process.argv[3] ?? join(
  HERE,
  'apps/service/src/HyperAgent/HyperAgentClient.g.cs',
)

const doc = JSON.parse(readFileSync(SNAPSHOT, 'utf8'))
const schemas = doc.components?.schemas ?? {}

// ── helpers ──────────────────────────────────────────────────────────

const pascal = (s) =>
  s
    .replace(/[^A-Za-z0-9_]/g, '')
    .replace(/_(.)/g, (_, c) => c.toUpperCase())
    .replace(/^(.)/, (_, c) => c.toUpperCase())

const refName = (ref) => ref.split('/').pop()

const csType = (schema, inModel = false) => {
  if (!schema) return 'object'
  if (schema.$ref) {
    const name = pascal(refName(schema.$ref).replace(/Dto$/, ''))
    return inModel ? name : `Models.${name}`
  }
  if (schema.type === 'array') return `IReadOnlyList<${csType(schema.items, inModel)}>`
  if (schema.type === 'object' || schema.properties) {
    const fields = Object.entries(schema.properties ?? {}).map(
      ([n, s]) => `${csType(s, inModel)} ${pascal(n)}`,
    )
    return `object /* { ${fields.join('; ')} } */`
  }
  switch (schema.type) {
    case 'string':
      return 'string'
    case 'integer':
      return 'long'
    case 'number':
      return 'double'
    case 'boolean':
      return 'bool'
  }
  return 'object'
}

const emitExceptionTypes = () => `// ── ProblemDetails exception hierarchy ─────────────────────────────────

public abstract class HyperAgentException : Exception
{
    public Uri TypeUri { get; }
    public int StatusCode { get; }
    public string? Detail { get; }

    protected HyperAgentException(Uri typeUri, int statusCode, string? detail, Exception? inner = null)
        : base(\$\"{typeUri} (HTTP {statusCode})\" + (detail is null ? \"\" : \": \" + detail), inner)
    {
        TypeUri = typeUri;
        StatusCode = statusCode;
        Detail = detail;
    }
}

public sealed class HyperAgentProblemException : HyperAgentException
{
    public HyperAgentProblemException(Uri typeUri, int statusCode, string? detail)
        : base(typeUri, statusCode, detail) { }
}

public sealed class HyperAgentMissingTokenException : HyperAgentException
{
    public HyperAgentMissingTokenException(Uri typeUri, int statusCode, string? detail)
        : base(typeUri, statusCode, detail) { }
}

public sealed class HyperAgentInvalidTokenException : HyperAgentException
{
    public HyperAgentInvalidTokenException(Uri typeUri, int statusCode, string? detail)
        : base(typeUri, statusCode, detail) { }
}

public sealed class HyperAgentInvalidDriveKeyException : HyperAgentException
{
    public HyperAgentInvalidDriveKeyException(Uri typeUri, int statusCode, string? detail)
        : base(typeUri, statusCode, detail) { }
}

public sealed class HyperAgentDriveNotMountedException : HyperAgentException
{
    public HyperAgentDriveNotMountedException(Uri typeUri, int statusCode, string? detail)
        : base(typeUri, statusCode, detail) { }
}

public sealed class HyperAgentRangeNotSatisfiableException : HyperAgentException
{
    public HyperAgentRangeNotSatisfiableException(Uri typeUri, int statusCode, string? detail)
        : base(typeUri, statusCode, detail) { }
}

public sealed class HyperAgentTransportException : Exception
{
    public HyperAgentTransportException(string message, Exception inner)
        : base(message, inner) { }
}

`

// ── generate client ──────────────────────────────────────────────────

const out = []

out.push(`// <auto-generated>
//     This code was generated from apps/hyper-agent/test/openapi.snapshot.json
//     by scripts/gen-hyper-agent-client.mjs.
//
//     Do not edit this file manually — it is regenerated on every CI run
//     against the Hyper Agent's OpenAPI contract. A diff in this file
//     means a controller changed without a paired regeneration. Re-run
//     \`pnpm regen:hyper-agent-client\` locally to update.
// </auto-generated>
#nullable enable
#pragma warning disable CS1591 // Missing XML comment for publicly visible type or member
using System;
using System.Collections.Generic;
using System.IO;
using System.Net;
using System.Net.Http;
using System.Net.Http.Headers;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Threading;
using System.Threading.Tasks;

namespace CineReel.Service.Infrastructure.HyperAgent.Generated;
`)

out.push(emitExceptionTypes())

out.push(`// ── Models ─────────────────────────────────────────────────────────────

public static class Models
{
`)

for (const [name, schema] of Object.entries(schemas)) {
  const required = new Set(schema.required ?? [])
  const props = Object.entries(schema.properties ?? {}).map(([pn, ps]) => {
    const t = csType(ps, true)
    const nullable = required.has(pn) ? '' : '?'
    return `        public ${t}${nullable} ${pascal(pn)} { get; set; }`
  })
  const propsBlock = props.length ? `\n${props.join('\n')}\n    ` : ''
  out.push(`    public sealed class ${pascal(name.replace(/Dto$/, ''))}
    {${propsBlock}}

`)
}

out.push(`}

// ── Client ────────────────────────────────────────────────────────────

public sealed partial class HyperAgentClient
{
    private readonly HttpClient _http;
    private readonly string _bearerToken;
    private static readonly JsonSerializerOptions JsonOpts = new()
    {
        PropertyNameCaseInsensitive = true,
    };

    public HyperAgentClient(HttpClient http, string bearerToken)
    {
        _http = http ?? throw new ArgumentNullException(nameof(http));
        _bearerToken = bearerToken ?? throw new ArgumentNullException(nameof(bearerToken));
    }

    public async Task<T> SendAsync<T>(HttpRequestMessage req, CancellationToken ct)
    {
        if (!string.IsNullOrEmpty(_bearerToken))
            req.Headers.Authorization = new AuthenticationHeaderValue("Bearer", _bearerToken);

        HttpResponseMessage resp;
        try
        {
            resp = await _http.SendAsync(req, HttpCompletionOption.ResponseContentRead, ct);
        }
        catch (Exception ex)
        {
            throw new HyperAgentTransportException("Hyper Agent unreachable: " + ex.Message, ex);
        }

        if (!resp.IsSuccessStatusCode)
        {
            var problem = await ReadProblemAsync(resp, ct);
            throw MapProblemException(problem, resp.StatusCode);
        }

        var media = resp.Content.Headers.ContentType?.MediaType ?? "";
        if (media.StartsWith("application/json"))
        {
            var raw = await resp.Content.ReadAsStringAsync(ct);
            if (string.IsNullOrWhiteSpace(raw)) return default!;
            return JsonSerializer.Deserialize<T>(raw, JsonOpts)!;
        }
        // Non-JSON (e.g. application/octet-stream for the files endpoint).
        if (typeof(T) == typeof(byte[]))
        {
            var bytes = await resp.Content.ReadAsByteArrayAsync(ct);
            return (T)(object)bytes;
        }
        return default!;
    }

    private static async Task<ProblemEnvelope?> ReadProblemAsync(HttpResponseMessage resp, CancellationToken ct)
    {
        var media = resp.Content.Headers.ContentType?.MediaType ?? "";
        if (!media.StartsWith("application/problem+json")) return null;
        var raw = await resp.Content.ReadAsStringAsync(ct);
        try { return JsonSerializer.Deserialize<ProblemEnvelope>(raw, JsonOpts); }
        catch { return null; }
    }

    private static HyperAgentException MapProblemException(ProblemEnvelope? env, HttpStatusCode status)
    {
        var type = env?.Type is { } t ? new Uri(t) : new Uri("about:blank");
        var detail = env?.Detail;
        if (type.ToString().EndsWith("/missing-token")) return new HyperAgentMissingTokenException(type, (int)status, detail);
        if (type.ToString().EndsWith("/invalid-token")) return new HyperAgentInvalidTokenException(type, (int)status, detail);
        if (type.ToString().EndsWith("/invalid-drive-key")) return new HyperAgentInvalidDriveKeyException(type, (int)status, detail);
        if (type.ToString().EndsWith("/drive-not-mounted")) return new HyperAgentDriveNotMountedException(type, (int)status, detail);
        if (type.ToString().EndsWith("/range-not-satisfiable")) return new HyperAgentRangeNotSatisfiableException(type, (int)status, detail);
        return new HyperAgentProblemException(type, (int)status, detail);
    }

    private static string BuildQueryString(params (string Name, object? Value)[] kvs)
    {
        var sb = new StringBuilder();
        var first = true;
        foreach (var (n, v) in kvs)
        {
            if (v is null) continue;
            if (!first) sb.Append('&');
            first = false;
            sb.Append(n).Append('=').Append(Uri.EscapeDataString(v.ToString() ?? ""));
        }
        return sb.Length == 0 ? "" : "?" + sb.ToString();
    }

    private sealed class ProblemEnvelope
    {
        [JsonPropertyName("type")] public string? Type { get; set; }
        [JsonPropertyName("detail")] public string? Detail { get; set; }
    }
`)

// operations
for (const [path, item] of Object.entries(doc.paths ?? {})) {
  for (const [method, op] of Object.entries(item)) {
    if (typeof op !== 'object' || op === null) continue
    if (['parameters', '$ref'].includes(method)) continue
    const opName = pascal(op.operationId ?? `${method}_${path}`)
    const parameters = op.parameters ?? []
    const pathParams = parameters.filter((p) => p.in === 'path')
    const queryParams = parameters.filter((p) => p.in === 'query')
    const headerParams = parameters.filter((p) => p.in === 'header')
    const ok = op.responses?.['200'] ?? op.responses?.['206'] ?? op.responses?.['201']
    const okSchema = ok?.content?.['application/json']?.schema
    const returnType = okSchema ? csType(okSchema) : null
    const isVoid = !okSchema
    const returnsTask = isVoid ? 'Task' : `Task<${returnType}>`
    const sendAsyncType = isVoid ? 'Unit' : returnType

    const args = []
    let url = path.replace(/\{(\w+)\}/g, (_, k) => {
      args.push(`string ${k}`)
      return `{${k}}`
    })
    for (const q of queryParams) {
      args.push(`${csType(q.schema ?? {})}? ${q.name} = null`)
    }
    for (const h of headerParams) {
      args.push(`${csType(h.schema ?? {})}? ${h.name} = null`)
    }
    args.push('CancellationToken ct = default')

    const qs = queryParams.length
      ? `\n        var qs = BuildQueryString(${queryParams
          .map((q) => `(${JSON.stringify(q.name)}, ${q.name})`)
          .join(', ')});`
      : ''

    const headerInits = headerParams.length
      ? '\n' +
        headerParams
          .map(
            (h) =>
              `        if (${h.name} is not null) req.Headers.TryAddWithoutValidation(${JSON.stringify(h.name)}, ${h.name}.ToString());`,
          )
          .join('\n')
      : ''

    // Build a C# verbatim interpolated string. `{{` and `}}` escape
    // literal braces; the interpolation tokens are the actual route
    // parameter names from the OpenAPI spec.
    //
    // Strategy: temporarily wrap each interpolation's identifier with
    // sentinel control characters, blanket-escape every `{` and `}`
    // in the path, then restore the original interpolation tokens.
    // This avoids any ambiguity about which braces belong to an
    // interpolation.
    const SENT_OPEN = '\u0001'
    const SENT_CLOSE = '\u0002'
    let csPathRaw = url.replace(
      /\{(\w+)\}/g,
      (_, k) => `{${SENT_OPEN}${k}${SENT_CLOSE}}`,
    )
    csPathRaw = csPathRaw.replace(/\{/g, '{{').replace(/\}/g, '}}')
    csPathRaw = csPathRaw.replace(
      new RegExp(`\\{\\{\\u0001([A-Za-z_][A-Za-z0-9_]*)\\u0002\\}\\}`, 'g'),
      '{$1}',
    )

    // Make sure every path parameter has a corresponding C# parameter
    // declared in the method signature. NSwag-otherwise would inject
    // the splice `{path}` but not declare the local. We emit the
    // parameter names below from `pathParams` + `queryParams` +
    // `headerParams`; the only one this matters for is the catch-all
    // `{path}` in `/v1/files/{driveKey}/{path}` which the snapshot
    // does NOT list as a `parameter` entry.
    const sigNames = new Set([
      ...pathParams.map((p) => p.name),
      ...queryParams.map((p) => p.name),
      ...headerParams.map((p) => p.name),
    ])
    const declared = new Set(pathParams.map((p) => p.name))
    // Catch-all splat: parameter name is `path`.
    const splatMatch = url.match(/\{(\w+)\}(?=\/[^/]*$|$)/)
    if (splatMatch && !declared.has(splatMatch[1])) {
      // The URL uses `{path}` as the catch-all. Ensure the method
      // signature has a `path` parameter; the caller already does so.
      sigNames.add(splatMatch[1])
    }
    void sigNames

    const qsSuffix = queryParams.length ? ' + qs' : ''

    out.push('\n')
    out.push(`    /// <summary><c>${method.toUpperCase()} ${path}</c></summary>\n`)
    out.push(`    public async ${returnsTask} ${opName}(${args.join(', ')})\n`)
    out.push(`    {${qs.replace(/\n/g, '\n')}\n`)
    out.push(`        using var req = new HttpRequestMessage(HttpMethod.${pascal(method.toLowerCase())}, $\@"`)
    out.push(csPathRaw)
    out.push(`"${qsSuffix});${headerInits}\n`)
    out.push(`        ${isVoid ? 'await' : 'return await'} SendAsync<${sendAsyncType}>(req, ct);\n`)
    out.push(`    }\n`)
  }
}

out.push(`
    public struct Unit { }
}
`)

mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, out.join('\n'))
// eslint-disable-next-line no-console
console.log(`[gen-hyper-agent-client] wrote ${OUT}`)
